bool GroupSkipped(const char* group) {
    const char* skip = std::getenv("LBP3_RES_SKIP");
    if (!skip) return false;
    const size_t n = std::strlen(group);
    for (const char* p = skip; (p = std::strstr(p, group)) != nullptr; p += n) {
        const bool startOk = p == skip || p[-1] == ',';
        const bool endOk = p[n] == '\0' || p[n] == ',';
        if (startOk && endOk) return true;
    }
    return false;
}

void ApplyRes1440(Module& m) {
    const char* res = std::getenv("LBP3_RES");
    if (!res || std::strcmp(res, "1440") != 0) return;
    // Check every enabled site first: a partial resize would leave mismatched targets.
    int bad = 0, enabled = 0;
    for (const ResPatch& p : kRes1440) {
        if (GroupSkipped(p.group)) continue;
        ++enabled;
        if (std::memcmp(m.Addr(p.offset), p.expect.data(), p.expect.size()) != 0) {
            std::fprintf(stderr, "[res] eboot.bin+0x%llx (%s): bytes differ, the 1440p patch set is NOT applied: %s\n",
                         static_cast<unsigned long long>(p.offset), p.group, p.what);
            ++bad;
        }
    }
    uint8_t* pool = m.Addr(0x5bf55);  // MOV EDX,0x6a200000: the Garlic pool size in FUN_0005bed0
    const uint8_t poolExpect[5] = {0xba, 0x00, 0x00, 0x20, 0x6a};
    const char* poolMb = std::getenv("LBP3_RES_POOL_MB");
    if (poolMb && std::memcmp(pool, poolExpect, 5) != 0) {
        std::fprintf(stderr, "[res] eboot.bin+0x5bf55 (pool): bytes differ, the 1440p patch set is NOT applied\n");
        ++bad;
    }
    if (bad) return;
    for (const ResPatch& p : kRes1440) {
        if (GroupSkipped(p.group)) continue;
        std::memcpy(m.Addr(p.offset), p.replace.data(), p.replace.size());
        std::fprintf(stderr, "[res] eboot.bin+0x%llx %s: %s\n", static_cast<unsigned long long>(p.offset), p.group, p.what);
    }
    if (poolMb) {
        const uint64_t mb = std::strtoull(poolMb, nullptr, 10);
        const uint32_t bytes = static_cast<uint32_t>(std::min<uint64_t>(((mb + 1) / 2) * 2, 3072) << 20);  // 2 MB aligned
        std::memcpy(pool + 1, &bytes, 4);
        std::fprintf(stderr, "[res] eboot.bin+0x5bf55 pool: Garlic 1698 -> %u MB\n", bytes >> 20);
    }
    std::fprintf(stderr, "[res] 1440p: %d sites patched (display 2560x1440; LBP3_RES_SKIP=%s)\n", enabled,
                 std::getenv("LBP3_RES_SKIP") ? std::getenv("LBP3_RES_SKIP") : "none");
}

